"""Builds the website's hero name table from HearthstoneJSON card data (T-510).

The site shows heroes by name, in English on /… and in the game's Spanish
(esES) on /es/… (D-086, D-092). It never fetches card data at run time, so
this script writes a small static table that is committed:
web/src/lib/heroes/names.data.ts. Only hero card ids and names go in it, no
text, art or other card data.

- Base heroes: every Battlegrounds hero card (`battlegroundsHero`), plus the
  retired or transformed hero cards of the Battlegrounds set that are not
  skins (Bartender Bob, placeholders and tutorial copies left out).
- Skins: every card with `battlegroundsSkinParentId` maps to its base hero.
  The site finds most of them by dropping `_SKIN_…` from the id; only the
  skins that rule gets wrong are listed.

Usage:
    python tools/hero_names.py              fetch both languages and write the table
    python tools/hero_names.py --from DIR   read DIR/enUS.json and DIR/esES.json instead
    python tools/hero_names.py --check      exit 1 if the committed table is out of date

Exit codes: 0 = written (or up to date), 1 = out of date or bad data, 2 = network error.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

USER_AGENT = "TavernLedger-tools (+https://tavernledger.net)"
URL = "https://api.hearthstonejson.com/v1/latest/{locale}/cards.json"
LOCALES = ("enUS", "esES")
TIMEOUT = 60.0
MAX_BYTES = 64 * 1024 * 1024
OUT = Path(__file__).resolve().parent.parent / "web" / "src" / "lib" / "heroes" / "names.data.ts"

CARD_ID = re.compile(r"^[A-Za-z0-9_]{1,64}$")
SKIN_SUFFIX = re.compile(r"_SKIN_[A-Za-z0-9]+$")
# Hero cards of the Battlegrounds set that are not heroes a player plays.
NOT_A_HERO = re.compile(r"^TB_BaconShopBob|_PH$|_Tutorial$")
# The real data has about 140 base heroes and 650 skins; far fewer means a bad answer.
MIN_BASES = 100
MIN_SKINS = 300


class DataError(Exception):
    """The card data is not what the table needs."""


def skin_rule(card_id: str) -> str:
    """The base id the website guesses for a skin: the id without `_SKIN_…`."""
    return SKIN_SUFFIX.sub("", card_id)


def _cards(data: object) -> list[dict]:
    if not isinstance(data, list):
        raise DataError("card data is not a list")
    return [c for c in data if isinstance(c, dict) and isinstance(c.get("id"), str) and CARD_ID.match(c["id"])]


def _is_base(card: dict) -> bool:
    if card.get("battlegroundsHero") is True:
        return True
    return (
        card.get("type") == "HERO"
        and card.get("set") == "BATTLEGROUNDS"
        and "battlegroundsSkinParentId" not in card
        and not NOT_A_HERO.search(card["id"])
    )


def _name(card: dict) -> str:
    name = card.get("name")
    if not isinstance(name, str) or not name.strip() or len(name) > 80:
        raise DataError(f"no usable name for {card['id']}")
    return name.strip()


def build_table(english: object, spanish: object) -> tuple[dict[str, tuple[str, str]], dict[str, str]]:
    """(names, skins): base id -> (English, Spanish) and skin id -> base id where the rule is wrong."""
    en = _cards(english)
    es = {c["id"]: c for c in _cards(spanish)}
    bases = {c["id"]: c for c in en if _is_base(c)}
    names: dict[str, tuple[str, str]] = {}
    for card_id, card in bases.items():
        other = es.get(card_id)
        if other is None:
            raise DataError(f"{card_id} has no Spanish card")
        names[card_id] = (_name(card), _name(other))
    by_dbf = {c["dbfId"]: c["id"] for c in bases.values() if isinstance(c.get("dbfId"), int)}
    skins: dict[str, str] = {}
    skin_count = 0
    for card in en:
        parent = card.get("battlegroundsSkinParentId")
        if parent is None or card["id"] in names:
            continue
        base = by_dbf.get(parent)
        if base is None:
            continue  # a skin of something that is not a hero (Bartender Bob's)
        skin_count += 1
        if skin_rule(card["id"]) != base:
            skins[card["id"]] = base
    if len(names) < MIN_BASES or skin_count < MIN_SKINS:
        raise DataError(f"too few heroes ({len(names)}) or skins ({skin_count}): not the full card data")
    return names, skins


def render(names: dict[str, tuple[str, str]], skins: dict[str, str]) -> str:
    def s(text: str) -> str:
        return json.dumps(text, ensure_ascii=False)

    lines = [
        "// Generated by tools/hero_names.py from HearthstoneJSON card data (enUS and",
        "// esES). Do not edit by hand: run the script again. Card names are",
        "// Blizzard's, used under its Fan Content Policy (PROVENANCE.md, D-092).",
        "",
        "/** Base hero card id -> [English name, Spanish (esES) name]. */",
        "export const HERO_NAMES: Readonly<Record<string, readonly [string, string]>> = {",
    ]
    lines += [f"  {s(k)}: [{s(en)}, {s(es)}]," for k, (en, es) in sorted(names.items())]
    lines += [
        "};",
        "",
        "/** Skins whose base hero is not their id without `_SKIN_…`. */",
        "export const HERO_SKINS: Readonly<Record<string, string>> = {",
    ]
    lines += [f"  {s(k)}: {s(v)}," for k, v in sorted(skins.items())]
    lines += ["};", ""]
    return "\n".join(lines)


def fetch(locale: str) -> object:
    request = urllib.request.Request(URL.format(locale=locale), headers={"User-Agent": USER_AGENT, "Accept": "application/json"})
    with urllib.request.urlopen(request, timeout=TIMEOUT) as response:
        if response.status != 200:
            raise DataError(f"{locale}: HTTP {response.status}")
        body = response.read(MAX_BYTES + 1)
    if len(body) > MAX_BYTES:
        raise DataError(f"{locale}: answer too large")
    return json.loads(body)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--from", dest="source", type=Path, help="folder with enUS.json and esES.json")
    parser.add_argument("--check", action="store_true", help="only say whether the committed table is up to date")
    args = parser.parse_args(argv)
    try:
        if args.source:
            data = [json.loads((args.source / f"{loc}.json").read_text(encoding="utf-8")) for loc in LOCALES]
        else:
            data = [fetch(loc) for loc in LOCALES]
        names, skins = build_table(*data)
        text = render(names, skins)
    except (urllib.error.URLError, TimeoutError, OSError) as err:
        print(f"could not read the card data: {err}", file=sys.stderr)
        return 2
    except (DataError, ValueError) as err:
        print(f"bad card data: {err}", file=sys.stderr)
        return 1
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.name} is out of date: run python tools/hero_names.py", file=sys.stderr)
            return 1
        print(f"{OUT.name} is up to date")
        return 0
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.name}: {len(names)} heroes, {len(skins)} listed skins")
    return 0


if __name__ == "__main__":
    sys.exit(main())
