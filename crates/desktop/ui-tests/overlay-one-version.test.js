"use strict";
// The overlay has one version (D-146): no Simple/Advanced mode in its page,
// its scripts, its stylesheet, its settings or its commands. The main
// window's own switch (detail-switch.test.js) is a separate thing.
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const UI = path.join(__dirname, "../ui");
const read = (file) => fs.readFileSync(path.join(UI, file), "utf8");
const OVERLAY_FILES = [
  "overlay.html",
  "overlay.css",
  "overlay.js",
  "overlay-hover.js",
  "overlay-layout.js",
  "overlay-words.js",
  "odds-words.js",
  "lobby-words.js",
  "counters-words.js",
  "strings/overlay.js",
];

test("no overlay file mentions a detail mode, Advanced or an Advanced-only class", () => {
  for (const file of OVERLAY_FILES) {
    const text = read(file);
    assert.doesNotMatch(text, /data-detail|dataset\.detail|overlay_set_detail|\bsimple-only\b|class="adv"|"adv"|\.adv\b|\bAdvanced\b|\bAvanzado\b/, file);
  }
});

test("the overlay page has no detail switch, in the page or in the main window's settings", () => {
  assert.doesNotMatch(read("overlay.html"), /detail/);
  assert.doesNotMatch(read("overlay-layout.js"), /detail/);
  assert.doesNotMatch(read("overlay-switch.js"), /detail/);
  const main = read("index.html");
  assert.doesNotMatch(main, /overlay-detail/);
  assert.match(main, /id="setting-window-detail"/, "the main window keeps its own switch");
});

test("the overlay's detail words are gone from both languages, the main window's stay", () => {
  const overlay = read("strings/overlay.js");
  assert.doesNotMatch(overlay, /"ov\.(toolbar\.)?detail/);
  assert.doesNotMatch(overlay, /"ov\.possible\./);
  const common = read("strings/common.js");
  assert.doesNotMatch(common, /"settings\.detail\.overlay"/);
  assert.match(common, /"win\.detail\.advanced"/);
});

test("no overlay command offers a mode", () => {
  const commands = fs.readFileSync(path.join(__dirname, "../app_commands.rs"), "utf8");
  assert.doesNotMatch(commands, /overlay_set_detail/);
  assert.match(commands, /app_set_window_detail/, "the main window's command stays");
  for (const file of ["main", "overlay"]) {
    const capability = fs.readFileSync(path.join(__dirname, `../capabilities/${file}.json`), "utf8");
    assert.doesNotMatch(capability, /overlay-set-detail/, file);
  }
  assert.equal(fs.existsSync(path.join(__dirname, "../permissions/autogenerated/overlay_set_detail.toml")), false);
});

test("the overlay's stylesheet has one width and one set of panel paddings", () => {
  const css = read("overlay.css");
  assert.match(css, /--stack-width: 13\.5rem;/);
  assert.doesNotMatch(css, /\.possible|\.kws?\b|\.next-block|\.seat-line|\.opponent\b/);
});
